//! What a simulated guest records about itself and what a process of guests writes at the end.

use crate::link::LinkSpec;
use crate::stats::{Samples, Summary};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct GuestReport {
    pub index: usize,
    pub name: String,
    pub edit: bool,
    pub link: LinkSpec,
    pub stuck: bool,
    /// Times in ms; `None` when the step was never reached.
    pub dial_ms: Option<f64>,
    pub welcome_ms: Option<f64>,
    pub snapshot_ms: Option<f64>,
    pub images_ms: Option<f64>,
    pub snapshot_kib: f64,
    pub images_mib: f64,
    pub joins: u32,
    pub drops: u32,
    pub dial_failures: u32,
    pub dial_errors: Vec<String>,
    /// Time from a lost connection to being welcomed back (ms), and how many of those needed a whole snapshot.
    pub resume_ms: Vec<f64>,
    pub resume_snapshots: u32,
    pub edits_sent: u64,
    pub edits_confirmed: u64,
    pub presence_sent: u64,
    pub transients_sent: u64,
    pub stroke_batches_sent: u64,
    pub chunks_sent: u64,
    pub undos_sent: u64,
    pub uploads_done: u64,
    pub uploads_refused: u64,
    pub rejected: BTreeMap<String, u32>,
    pub superseded: u64,
    pub pending_discarded: u64,
    pub frames_in: u64,
    pub bytes_in: u64,
    pub frames_out: u64,
    pub bytes_out: u64,
    pub link_dropped: u64,
    pub decode_errors: u64,
    pub max_backlog: u64,
    pub max_step_ms: f64,
    /// Seconds of CPU the guest's own protocol work took (decode, validation, apply), measured around the handling of frames.
    pub handle_ms_total: f64,
    pub end: String,
    pub closed: Option<String>,
    pub digest: String,
    pub last_seq: u64,
    pub pending: usize,
    pub objects: usize,
    #[serde(skip)]
    pub rtt_ms: Samples,
    #[serde(skip)]
    pub visible_ms: Samples,
    #[serde(skip)]
    pub cursor_ms: Samples,
}

/// What `crowd guests` writes: all the guests of one process, aggregated.
#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct FleetReport {
    pub machine: String,
    pub seed: u64,
    pub guests: usize,
    pub started_epoch_ms: u64,
    pub duration_s: f64,
    pub profile: serde_json::Value,
    pub transport: String,
    pub rtt_ms: Summary,
    pub visible_ms: Summary,
    pub cursor_ms: Summary,
    /// The same for the guests on a degraded link (apart: they would blur the others).
    pub slow_rtt_ms: Summary,
    pub slow_visible_ms: Summary,
    pub slow_cursor_ms: Summary,
    pub snapshot_ms: Summary,
    pub slow_snapshot_ms: Summary,
    pub welcome_ms: Summary,
    pub images_ms: Summary,
    pub dial_ms: Summary,
    pub resume_ms: Summary,
    pub snapshot_kib: Summary,
    pub bytes_in: u64,
    pub bytes_out: u64,
    pub frames_in: u64,
    pub frames_out: u64,
    pub edits_sent: u64,
    pub edits_confirmed: u64,
    pub drops: u64,
    pub resume_snapshots: u64,
    pub joined: usize,
    pub never_joined: usize,
    pub closed_by_host: usize,
    pub converged: usize,
    pub diverged: usize,
    pub rejected: BTreeMap<String, u32>,
    pub peak_rss_mib: f64,
    pub peak_cpu_cores: f64,
    pub per_guest: Vec<GuestReport>,
}

/// What the host side (a test of the application) writes: `host.json`.
#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct HostReport {
    pub board_objects: usize,
    pub board_pages: usize,
    pub board_json_mib: f64,
    pub board_asset_mib: f64,
    pub board_images: usize,
    pub transport: String,
    /// `bare` (session host + editor) or `app` (the whole application, one egui frame per turn).
    pub mode: String,
    pub max_participants: usize,
    pub host_activity: bool,
    pub started_epoch_ms: u64,
    pub t0_epoch_ms: u64,
    pub duration_s: f64,
    /// Duration of one turn of the host loop (`SessionHost::poll` and what the host does around it; in `app` mode a whole frame), ms,
    /// and the interval between two turns.
    pub turn_ms: Summary,
    pub turn_gap_ms: Summary,
    pub turn_over_16_pct: f64,
    pub turn_over_50_pct: f64,
    pub cpu_cores: Summary,
    pub peak_cpu_cores: f64,
    pub rss_mib: Summary,
    pub peak_rss_mib: f64,
    pub rss_start_mib: f64,
    pub rss_end_mib: f64,
    pub machine_cpu_pct: Summary,
    pub tx_mib: f64,
    pub rx_mib: f64,
    pub tx_mib_s: Summary,
    pub rx_mib_s: Summary,
    pub frames_tx: u64,
    pub frames_rx: u64,
    pub send_errors: BTreeMap<String, u64>,
    /// Bytes waiting in the outgoing queue of the worst connection at each sample (KiB).
    pub queue_kib_worst: Summary,
    pub queue_kib_total_max: f64,
    pub members_peak: usize,
    pub connections_peak: usize,
    pub joined: u64,
    pub left: u64,
    pub excluded: u64,
    pub warned: u64,
    pub warnings: BTreeMap<String, u64>,
    pub excluded_reasons: BTreeMap<String, u64>,
    pub seq_final: u64,
    pub log_entries: usize,
    pub log_kib: f64,
    pub tracked_objects: usize,
    pub objects_final: usize,
    pub digest: String,
    pub host_edits: u64,
}
