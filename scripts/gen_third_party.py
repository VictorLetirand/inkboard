#!/usr/bin/env python3
"""Generates THIRD_PARTY_LICENSES.md: licenses of the dependencies embedded in the executables (excluding test dependencies), with the actual license texts.

Usage: python scripts/gen_third_party.py   (from the repository root; requires cargo)
The dependencies are the production ones for Windows, Linux and macOS; the texts are read from the crates' sources (cargo registry).
"""
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGETS = ['x86_64-pc-windows-msvc', 'x86_64-unknown-linux-gnu', 'aarch64-apple-darwin']
LICENSE_FILE = re.compile(r'^(LICENSE|LICENCE|COPYING|NOTICE|UNLICENSE|OFL)([-_.].*)?(\.(txt|md))?$', re.I)
PERMISSIVE = ('MIT', 'Apache-2.0', 'BSD', 'ISC', 'Zlib', 'Unicode', 'OFL', 'BSL-1.0', 'Unlicense', '0BSD', 'Ubuntu-font', 'LLVM-exception', 'CC0')


def run(*args):
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True, encoding='utf-8').stdout


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    meta = json.loads(run('cargo', 'metadata', '--format-version', '1', '--locked'))
    members = {p['id'] for p in meta['packages'] if p['source'] is None}
    by_key = {(p['name'], p['version']): p for p in meta['packages']}
    wanted = set()
    for t in TARGETS:
        out = run('cargo', 'tree', '--workspace', '-e', 'normal,build', '--target', t, '--prefix', 'none', '--no-dedupe', '-f', '{p}')
        for line in out.splitlines():
            m = re.match(r'^(\S+) v(\S+)', line.strip())
            if m:
                wanted.add((m.group(1), m.group(2)))
    pkgs = [by_key[k] for k in sorted(wanted) if k in by_key and by_key[k]['id'] not in members]

    texts = {}  # hash -> (texte, [crates])
    rows = []
    problems = []
    no_file = []
    for p in pkgs:
        lic = p.get('license') or 'inconnue'
        rows.append((p['name'], p['version'], lic, p.get('repository') or ''))
        if not any(tok in lic for tok in PERMISSIVE):
            problems.append(f"{p['name']} {p['version']} : {lic}")
        base = os.path.dirname(p['manifest_path'])
        found = 0
        for dirpath, dirs, files in os.walk(base):
            if dirpath[len(base):].count(os.sep) > 3:
                dirs[:] = []
                continue
            dirs[:] = [d for d in dirs if d not in ('target', 'tests', 'benches', 'examples', '.git')]
            for f in files:
                if LICENSE_FILE.match(f):
                    try:
                        t = open(os.path.join(dirpath, f), encoding='utf-8', errors='replace').read().strip()
                    except OSError:
                        continue
                    if not t:
                        continue
                    h = hashlib.sha256(re.sub(r'\s+', ' ', t).encode()).hexdigest()
                    texts.setdefault(h, (t, []))[1].append(f"{p['name']} {p['version']}")
                    found += 1
        if not found:
            no_file.append((p['name'], p['version'], lic, p.get('repository') or ''))

    out = ['# Third-party licenses', '',
           "Inkboard's executables embed the libraries below (production dependencies on Windows, Linux and macOS). Each remains under its own license,",
           "all permissive. This file is generated by `scripts/gen_third_party.py`.", '',
           '## Embedded fonts', '',
           '- **STIX Two Math** (LaTeX formula typesetting, through the `latex-rust` library): SIL Open Font License 1.1 — text below.',
           "- **egui's default fonts** (`epaint_default_fonts`: Hack, Ubuntu-Light, NotoEmoji, emoji-icon-font): MIT, Ubuntu Font Licence 1.0 and SIL OFL 1.1 — texts below.",
           "- System fonts (Segoe UI, Georgia, etc.) are **not** embedded: they are read from the user's machine.", '',
           f'## Libraries ({len(rows)})', '', '| Crate | Version | License | Repository |', '|---|---|---|---|']
    out += [f'| {n} | {v} | {l} | {r} |' for n, v, l, r in rows]
    if no_file:
        out += ['', f'### No license file in their package ({len(no_file)})', '',
                "These crates declare a standard SPDX license (MIT, Apache-2.0, Zlib, BSL-1.0: texts below) but ship no file; the authors' names and copyright are in their repository.", '']
        out += [f'- {n} {v} — {l} — {r}' for n, v, l, r in no_file]
    out += ['', '## License texts', '']
    for i, (t, crates) in enumerate(sorted(texts.values(), key=lambda x: x[1][0].lower()), 1):
        names = sorted(set(crates))
        shown = ', '.join(names[:12]) + (f' … (+{len(names) - 12})' if len(names) > 12 else '')
        out += [f'### Text {i} — {shown}', '', '```text', t, '```', '']
    path = os.path.join(ROOT, 'THIRD_PARTY_LICENSES.md')
    open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    print(f'{len(rows)} libraries ({len(no_file)} without a license file in the package), {len(texts)} distinct texts -> {path}')
    if problems:
        print('TO REVIEW:')
        for pr in problems:
            print('  -', pr)
        sys.exit(1)


if __name__ == '__main__':
    main()
